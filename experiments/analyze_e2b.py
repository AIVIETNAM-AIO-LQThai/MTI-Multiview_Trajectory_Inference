"""E2b analysis: K1/K2/K3 for the selected priors, harm/improvement counts over the 30 truths, retained-benefit shares, A4 (saved checkpoints),
and the descriptive lag-0 overstatement check.   python experiments/analyze_e2b.py -> docs/reports/e2b_tables.md, results/e2b/analysis.json
"""
from __future__ import annotations

import argparse
import json
import os

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["qbar", "K1", "K2", "K3", "plausible", "naive"]
LABEL = {"qbar": "q̄ (mean prior)", "K1": "grid Bayes (K1)", "K2": "no-harm (K2)", "K3": "minimax regret (K3)", "plausible": "'most plausible' (β=.2, α=.5)", "naive": "naive (β=0)"}


def tci(x):
    x = np.asarray(x, float)
    return float(x.mean()), float(stats.t.ppf(0.975, len(x) - 1) * x.std(ddof=1) / np.sqrt(len(x)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "reports", "e2b_tables.md"))
    args = ap.parse_args()
    R = json.load(open(os.path.join(ROOT, "results", "e2b", "e2b.json")))
    truths = R["truths"]
    nT = len(truths)
    prov = R["provenance"]
    md = [f"# E2b tables (generated by `experiments/analyze_e2b.py`; protocol docs/e2_protocol.md §10)\n",
          f"Code `{prov['git_commit'][:8]}` (dirty code: {prov['dirty_code'] or 'none'}). Uncertainty set: β_t ∈ {{0.02,0.05,0.1,0.2,0.35,0.5}} × α_t ∈ {{0,0.25,0.5,0.75,1}} (30 channels, uniform weights). "
          f"Mean prior q̄ = (β̄ = {R['qbar']['beta']:.4f}, ᾱ = {R['qbar']['alpha']:.3f}).\n"]
    out = {}
    hyp_rows = []
    for p in (0, 1):
        D = R[f"phys{p}"]
        sel, picks, conf = D["selection"], D["picks"], D["confirm"]
        qw = sel["q_w"]
        E, B, SE, dl = (np.array(sel[k]) for k in ("E", "B", "SE", "delta"))
        cands = sel["cand"]
        k1, k3, k2 = E.mean(axis=1), E.max(axis=1), B.min(axis=1)
        md.append(f"## Physics q_w = {qw}\n")
        md.append("### Selection (screening prefixes, master 8101, 100k; exact clean law)\n")
        md.append(f"{len(cands)} candidate priors; {picks['n_no_harm']} satisfy the no-harm condition (B_t ≥ −Δ_t for all 30 truths). q̄ has K1 = {k1[-1]:.5f}; the best grid candidate has K1 = {k1.min():.5f} "
                  f"(β={cands[picks['K1']]['beta']:g}, α={cands[picks['K1']]['alpha']:g}); every grid candidate satisfies K1 ≥ K1(q̄) − {max(0.0, k1[-1] - k1.min()):.2g}.\n")
        md.append("| prior | β_a | α_a | K1 (Bayes risk) | K2 (min_t B) | K3 (max_t regret) |\n|---|---|---|---|---|---|")
        idx = {"qbar": picks["qbar"], "K1": picks["K1"], "K2": picks["K2"], "K3": picks["K3"]}
        for nm, i in idx.items():
            md.append(f"| {LABEL[nm]} | {cands[i]['beta']:.4f} | {cands[i]['alpha']:.3f} | {k1[i]:.5f} | {k2[i]:+.4f} | {k3[i]:.4f} |")
        for nm, bb, aa in (("plausible", 0.2, 0.5), ("naive", 0.0, 0.0)):
            i = next(j for j, c in enumerate(cands) if abs(c["beta"] - bb) < 1e-9 and abs(c["alpha"] - aa) < 1e-9)
            md.append(f"| {LABEL[nm]} | {bb:g} | {aa:g} | {k1[i]:.5f} | {k2[i]:+.4f} | {k3[i]:.4f} |")
            idx[nm] = i
        out[f"phys{p}|selection"] = {nm: dict(K1=float(k1[i]), K2=float(k2[i]), K3=float(k3[i])) for nm, i in idx.items()}
        # descriptive hypothesis data
        q0a, q0t = np.array(sel["q0_a"]), np.array(sel["q0_t"])
        beta_a = np.array([c["beta"] for c in cands])
        beta_t = np.array([t[0] for t in truths])
        V2 = np.array(conf["V2"]) if False else None
        v2_sel = np.array(sel["V2"])
        for i in range(len(cands)):
            if beta_a[i] == 0:
                continue
            for t in range(nT):
                hyp_rows.append((p, q0a[i] / q0t[t], beta_a[i] / beta_t[t], B[i, t], SE[i, t], v2_sel[t], dl[t]))

        md.append("\n### Confirmation, exact clean law (independent prefixes, master 8201, 20k): all 30 truths\n")
        md.append("Harm = CI_hi(B) < −Δ_t; improvement = CI_lo(B) > Δ_t; Δ_t = clip(0.10 V₂,t, 0.002 VOI, 0.02 VOI) on this set. Retained = B_t / V₂,t (matched composition retains 100%).\n")
        V2c, dlc = np.array(conf["V2"]), np.array(conf["delta"])
        md.append("| prior (β_a, α_a) | K1 | K2 = min_t B | K3 | truths: material harm | material improvement | other | median retained | worst-truth retained |\n|---|---|---|---|---|---|---|---|---|")
        for nm in ORDER:
            sc = np.array(conf["scores"][nm])           # (30, 3): E, B, se
            Eb, Bb, se = sc[:, 0], sc[:, 1], sc[:, 2]
            harm = int(np.sum(Bb + 1.96 * se < -dlc)); imp = int(np.sum(Bb - 1.96 * se > dlc))
            ret = Bb / V2c
            spc = conf["spec"].get(nm, dict(beta=0.0, alpha=0.0))
            md.append(f"| {LABEL[nm]} ({spc['beta']:.3f}, {spc['alpha']:.3f}) | {Eb.mean():.5f} | {Bb.min():+.4f} | {Eb.max():.4f} | {harm} | {imp} | {nT - harm - imp} | {np.median(ret):.2f} | {ret.min():+.2f} |")
            out[f"phys{p}|confirm|{nm}"] = dict(K1=float(Eb.mean()), K2=float(Bb.min()), K3=float(Eb.max()), harm=harm, improvement=imp, median_retained=float(np.median(ret)), worst_retained=float(ret.min()))
        md.append("")
        if p == 0:
            md.append("**Truth-wise retained benefit B_t/V₂,t on the confirmation set** (rows: true β, columns: true α)\n")
            md.append("| prior | β_t \\ α_t | " + " | ".join(f"{a:g}" for a in (0, 0.25, 0.5, 0.75, 1)) + " |\n|---|---|" + "---|" * 5)
            for nm in ("qbar", "K3", "plausible"):
                sc = np.array(conf["scores"][nm])
                for bi, bt in enumerate((0.02, 0.05, 0.1, 0.2, 0.35, 0.5)):
                    cells = [f"{sc[bi * 5 + ai, 1] / V2c[bi * 5 + ai]:+.2f}" for ai in range(5)]
                    md.append(f"| {LABEL[nm] if bi == 0 else ''} | {bt:g} | " + " | ".join(cells) + " |")
            md.append("")

    # --- A4 with saved checkpoints
    md.append("## A4 (clean density, saved E2 checkpoints, no retraining), lead physics: priors from the lead-physics selection\n")
    D0 = R["phys0"]["confirm"]
    V2c, dlc = np.array(D0["V2"]), np.array(D0["delta"])
    for N in (1000, 100000):
        units = [u for u in R["a4"] if u["N"] == N]
        md.append(f"**N = {N}** ({len(units)} seeds; seed-level 95% t-interval, conditional on the shared confirmation set)\n")
        md.append("| prior | K1 | K2 = min_t B_pipe | K3 | truths: material harm | material improvement | other |\n|---|---|---|---|---|---|---|")
        base = np.array([u["E"]["naive"] for u in units])           # (seeds, 30)
        for nm in ORDER:
            Eu = np.array([u["E"][nm] for u in units])
            Bu = base - Eu
            k1m, k1h = tci(Eu.mean(axis=1))
            k3m, k3h = tci(Eu.max(axis=1))
            bm = Bu.mean(axis=0)
            bh = np.array([tci(Bu[:, t])[1] for t in range(nT)])
            harm = int(np.sum(bm + bh < -dlc)); imp = int(np.sum(bm - bh > dlc))
            md.append(f"| {LABEL[nm]} | {k1m:.4f} ± {k1h:.4f} | {bm.min():+.4f} | {k3m:.4f} ± {k3h:.4f} | {harm} | {imp} | {nT - harm - imp} |")
            out[f"a4|{N}|{nm}"] = dict(K1=k1m, K3=k3m, K2=float(bm.min()), harm=harm, improvement=imp)
        md.append("")

    # --- descriptive lag-0 check
    H = np.array(hyp_rows)
    ph, r0, rb, Bv, se, v2, dd = (H[:, i] for i in range(7))
    harmed = Bv + 1.96 * se < 0
    md.append("## Descriptive check: does harm track overstatement of the lag-0 corruption rate? (all selection pairs with β_a > 0, both physics)\n")
    md.append(f"{len(H):,} (candidate, truth) pairs; {int(harmed.sum()):,} with B_exact significantly below 0 (CI_hi < 0). x = declared / true corruption mass on the last action (lag 0); y = declared / true overall β.\n")
    edges = [0, 1, 1.5, 2, 3, 5, 10, 1e9]
    for nm, x in (("lag-0 rate ratio", r0), ("overall β ratio", rb)):
        md.append(f"| {nm} bin | pairs | share with B < 0 (significant) | median B/V₂,t |\n|---|---|---|---|")
        for lo, hi in zip(edges[:-1], edges[1:]):
            m = (x > lo) & (x <= hi) if lo > 0 else (x <= hi)
            if m.sum():
                md.append(f"| ({lo:g}, {hi:g}] | {int(m.sum())} | {harmed[m].mean():.3f} | {np.median(Bv[m] / v2[m]):+.2f} |")
        md.append("")
    first_r0, first_rb = float(r0[harmed].min()), float(rb[harmed].min())
    md.append(f"Smallest lag-0 ratio with significant harm: {first_r0:.2f}; smallest overall-β ratio with significant harm: {first_rb:.2f}. Among pairs with lag-0 ratio ≤ 1, harmed share = {harmed[r0 <= 1].mean():.4f}; with β ratio ≤ 1: {harmed[rb <= 1].mean():.4f}.\n")
    out["hyp|first_harm_lag0_ratio"], out["hyp|first_harm_beta_ratio"] = first_r0, first_rb
    for name, x in (("lag-0 ratio", r0), ("β ratio", rb)):                       # simple rank separation (AUC) of harmed vs not harmed
        pos, neg = x[harmed], x[~harmed]
        auc = float(stats.mannwhitneyu(pos, neg, alternative="greater").statistic / (len(pos) * len(neg)))
        md.append(f"AUC of the {name} for separating harmed from non-harmed pairs: {auc:.3f}.")
        out[f"hyp|auc|{name}"] = auc
    md.append("")
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(1, 2, figsize=(11, 4))
        sub = np.random.default_rng(0).choice(len(H), size=min(20000, len(H)), replace=False)
        for a_, x, lab in ((ax[0], r0, "declared / true lag-0 corruption mass"), (ax[1], rb, "declared / true β")):
            a_.scatter(np.log10(x[sub] + 1e-9), (Bv / v2)[sub], s=2, c=np.where(harmed[sub], "tab:red", "tab:blue"), alpha=0.4)
            a_.axhline(0, color="k", lw=0.6)
            a_.axvline(0, color="gray", ls=":")
            a_.set_xlabel(f"log10({lab})")
            a_.set_ylim(-3, 1.2)
        ax[0].set_ylabel("B_exact / V₂,t (1 = matched)")
        fig.tight_layout()
        fig.savefig(os.path.join(os.path.dirname(args.out), "fig_e2b_hypothesis.png"), dpi=110)
        plt.close(fig)
    except Exception as e:
        md.append(f"(figure skipped: {e})")
    open(args.out, "w", encoding="utf-8").write("\n".join(md) + "\n")
    json.dump(out, open(os.path.join(ROOT, "results", "e2b", "analysis.json"), "w"), indent=1)
    print("wrote", args.out)


if __name__ == "__main__":
    main()
