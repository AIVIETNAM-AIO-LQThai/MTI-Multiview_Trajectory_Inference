"""E3 analysis (protocol docs/e3_protocol.md section 5): controls, learning curves, crossover (Q1), harm rates (Q2), shrinkage (Q3),
moment baseline (Q4), absorption (Q5), off-family truths (Q6), learned clean laws.   python experiments/analyze_e3.py
Cost-type differences d = E_x - E_y (negative: x better). x materially better: CI_hi(d) < -Delta_t; materially worse: CI_lo(d) > Delta_t.
Harm: B_pipe = E_naive(same clean-law source) - E < -Delta_t. Intervals: 95% t over replicates (paired within a replicate), conditional on the shared
evaluation set. Wilson 95% intervals for rates.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADAPT = ["MLE", "MAP", "PP", "MOM"]
FIXED = ["naive", "F-qbar", "F-noharm", "F-minimax"]
TRUTH_DESC = {"T0": "β=0", "T1": "β=.02 α=0", "T2": "β=.05 α=.25", "T3": "β=.2 α=.5", "T4": "β=.35 α=1", "T5": "β=.125 lag-1 point", "T6": "β=.2 geometric", "T7": "β=.3 lag0+lag7"}


def tci(x):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    n = len(x)
    if n < 2:
        return float(x.mean()) if n else float("nan"), float("nan")
    return float(x.mean()), float(stats.t.ppf(0.975, n - 1) * x.std(ddof=1) / np.sqrt(n))


def wilson(k, n, z=1.96):
    if n == 0:
        return float("nan"), float("nan"), float("nan")
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def load(d):
    U = {}
    for p in glob.glob(os.path.join(d, "units", "*.json")):
        u = json.load(open(p))
        U[(u["source"], u["truth"])] = u
    return U


def arr(u, k):
    return np.array(u["A"][k], dtype=float)         # (reps, ns, 4)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "reports", "e3_tables.md"))
    args = ap.parse_args()
    base = os.path.join(ROOT, "results", "e3")
    U = load(base)
    prov = next(iter(U.values()))["provenance"]
    md = [f"# E3 tables (generated by `experiments/analyze_e3.py`; protocol docs/e3_protocol.md)\n",
          f"Code `{prov['git_commit'][:8]}` + patch `{prov['patch_sha256']}`. Estimators: MLE (EM), MAP (κ₀ = 30 toward q̄), PP (grid posterior predictive), MOM (pair-sum moments).\n"]
    out = {}
    truths = sorted({t for (_, t) in U if t.startswith("T")})

    def fixed_E(u, name):
        return u["fixed"][name]

    # ---------------- 1. identification controls
    md.append("## 1. Identification controls (exact clean law, 20 replicates; mean over replicates)\n")
    md.append("Gap = E (regret under the true channel); ORACLE-q has regret 0. `β̂`, `TV` = estimated rate and total variation of the estimated location distribution from the truth.\n")
    ctrl_rows = []
    for key in ("ctrlL1__b0.1", "ctrlL1__b0.3", "ctrlL2__a10", "ctrlL2__a55"):
        nm, tn = key.split("__")
        u = U.get((nm, tn))
        if not u:
            continue
        E, bh, tv = arr(u, "E"), arr(u, "bhat"), arr(u, "tv")
        md.append(f"**{nm} truth {tn}** (β = {u['truth_beta']:.2f}, q = {np.round(u['truth_q'], 3).tolist()}; naive regret {u['E_naive_pipe']:.4f}, F-qbar {u['fixed']['F-qbar']:.4f})\n")
        md.append("| n | " + " | ".join(f"{e}: regret / β̂ / TV" for e in ADAPT) + " |\n|---|" + "---|" * 4)
        for ni, n in enumerate(u["ns"]):
            if n in (10, 100, 1000, 10000):
                cells = [f"{np.nanmean(E[:, ni, k]):.4f} / {np.nanmean(bh[:, ni, k]):.3f} / {np.nanmean(tv[:, ni, k]):.3f}" if not np.all(np.isnan(tv[:, ni, k])) else f"{np.nanmean(E[:, ni, k]):.4f} / {np.nanmean(bh[:, ni, k]):.3f} / —" for k in range(4)]
                md.append(f"| {n} | " + " | ".join(cells) + " |")
        md.append("")
        out[f"ctrl|{key}|E_final"] = {e: float(np.nanmean(E[:, -1, k])) for k, e in enumerate(ADAPT)}
        out[f"ctrl|{key}|bhat_final"] = {e: float(np.nanmean(bh[:, -1, k])) for k, e in enumerate(ADAPT)}
        out[f"ctrl|{key}|tv_final"] = {e: float(np.nanmean(tv[:, -1, k])) for k, e in enumerate(ADAPT)}
        out[f"ctrl|{key}|V2"] = u["V2"]
    u3 = U.get(("EX", "T3"))
    if u3:
        bh = arr(u3, "bhat")
        md.append(f"**Positive control, L=8 exact law, truth T3 (β=0.2):** MLE β̂ at n=10,000 = {np.nanmean(bh[:, -1, 0]):.4f} (replicate sd {np.nanstd(bh[:, -1, 0], ddof=1):.4f}); regret {np.nanmean(arr(u3, 'E')[:, -1, 0]):.5f} vs naive {u3['V2']:.4f}.\n")
        out["ctrl|L8_T3|bhat_MLE_n10000"] = float(np.nanmean(bh[:, -1, 0]))

    # ---------------- 2/3. learning curves (EX) and crossover
    md.append("## 2. Learning curves with the exact clean law (EX): regret, mean ± 95% t over 20 replicates\n")
    md.append("Fixed references: naive; F-qbar (E2b mean-prior declaration); ORACLE-q = 0. Δ_t = margin.\n")
    for tn in truths:
        u = U.get(("EX", tn))
        if not u:
            continue
        E = arr(u, "E")
        md.append(f"**{tn} ({TRUTH_DESC[tn]})** — naive {u['E_naive_pipe']:.4f}, F-qbar {u['fixed']['F-qbar']:.4f}, F-noharm {u['fixed']['F-noharm']:.4f}, F-minimax {u['fixed']['F-minimax']:.4f}, Δ_t {u['delta']:.4f}\n")
        md.append("| n | " + " | ".join(ADAPT) + " |\n|---|" + "---|" * 4)
        for ni, n in enumerate(u["ns"]):
            md.append(f"| {n} | " + " | ".join("{:.4f} ± {:.4f}".format(*tci(E[:, ni, k])) for k in range(4)) + " |")
        md.append("")
        out[f"curve|EX|{tn}"] = {e: np.nanmean(E[:, :, k], axis=0).tolist() for k, e in enumerate(ADAPT)}

    md.append("## 3. Q1 crossover: smallest n at which the estimator is materially better than F-qbar (paired by replicate), and any n where it is materially worse\n")
    md.append("| truth | " + " | ".join(f"{e}: first better / any worse" for e in ADAPT) + " |\n|---|" + "---|" * 4)
    for tn in truths:
        u = U.get(("EX", tn))
        if not u:
            continue
        E, fq, d = arr(u, "E"), u["fixed"]["F-qbar"], u["delta"]
        cells = []
        for k, e in enumerate(ADAPT):
            first, worse = None, []
            for ni, n in enumerate(u["ns"]):
                m, h = tci(E[:, ni, k] - fq)
                if m + h < -d and first is None:
                    first = n
                if m - h > d:
                    worse.append(n)
            cells.append(f"{first if first else 'never'} / {worse if worse else '—'}")
            out[f"q1|EX|{tn}|{e}"] = dict(first_better=first, worse=worse)
        md.append(f"| {tn} ({TRUTH_DESC[tn]}) | " + " | ".join(cells) + " |")
    md.append("")

    # ---------------- Q2 harm rates
    def harm_counts(u, k, ni):
        Bp = u["E_naive_pipe"] - arr(u, "E")[:, ni, k]
        return int(np.sum(Bp < -u["delta"])), len(Bp)

    md.append("## 4. Q2 harm rates: share of replicates with B_pipe < −Δ_t (Wilson 95%); headline = worst truth\n")
    md.append("**Exact clean law (EX), per truth at selected n** (fixed declarations: harmed ✓/—):\n")
    nsel = (10, 30, 100, 1000, 10000)
    md.append("| truth | estimator | " + " | ".join(f"n={n}" for n in nsel) + " |\n|---|---|" + "---|" * len(nsel))
    for tn in truths:
        u = U.get(("EX", tn))
        if not u:
            continue
        for k, e in enumerate(ADAPT):
            cells = []
            for n in nsel:
                ni = u["ns"].index(n)
                kk, nn = harm_counts(u, k, ni)
                p, lo, hi = wilson(kk, nn)
                cells.append(f"{p:.2f} [{lo:.2f},{hi:.2f}]")
            md.append(f"| {tn} | {e} | " + " | ".join(cells) + " |")
        fx = " ".join(f"{f}:{'✓' if u['E_naive_pipe'] - u['fixed'][f] < -u['delta'] else '—'}" for f in FIXED[1:])
        md.append(f"| {tn} | fixed | {fx} | | | | |")
    md.append("\n**Worst-truth harm rate** (max over the 8 truths) by clean-law source group:\n")
    groups = {"EX": ["EX"], "ETA−": ["ETA-"], "ETA+": ["ETA+"], "HMM-10³ (s1)": ["HMM-1000-s1"], "HMM-10⁵ (s1)": ["HMM-100000-s1"]}
    md.append("| source | estimator | " + " | ".join(f"n={n}" for n in nsel) + " |\n|---|---|" + "---|" * len(nsel))
    for gname, srcs in groups.items():
        for k, e in enumerate(ADAPT):
            cells = []
            for n in nsel:
                worst, wt = -1.0, None
                for tn in truths:
                    u = U.get((srcs[0], tn))
                    if not u:
                        continue
                    kk, nn = harm_counts(u, k, u["ns"].index(n))
                    if kk / nn > worst:
                        worst, wt = kk / nn, tn
                cells.append(f"{worst:.2f} ({wt})")
                out[f"harm_worst|{gname}|{e}|{n}"] = dict(rate=worst, truth=wt)
            md.append(f"| {gname} | {e} | " + " | ".join(cells) + " |")
    md.append("\nFixed declarations, worst-truth harm (exact law): " + "; ".join(
        f"{f}: harmed truths {[tn for tn in truths if U.get(('EX', tn)) and U[('EX', tn)]['E_naive_pipe'] - U[('EX', tn)]['fixed'][f] < -U[('EX', tn)]['delta']]}" for f in FIXED[1:]) + "\n")

    # ---------------- Q3, Q4
    md.append("## 5. Q3 shrinkage (MAP − MLE) and Q4 efficiency (MOM / MLE regret ratio), exact law\n")
    md.append("| truth | n | MAP−MLE regret (95% CI) | verdict | MOM / MLE ratio |\n|---|---|---|---|---|")
    for tn in truths:
        u = U.get(("EX", tn))
        if not u:
            continue
        E = arr(u, "E")
        for n in (10, 30, 100, 300, 1000, 10000):
            ni = u["ns"].index(n)
            m, h = tci(E[:, ni, 1] - E[:, ni, 0])
            v = "MAP better" if m + h < -u["delta"] else ("MLE better" if m - h > u["delta"] else "equivalent/inconclusive")
            md.append(f"| {tn} | {n} | {m:+.4f} ± {h:.4f} | {v} | {np.nanmean(E[:, ni, 3]) / max(np.nanmean(E[:, ni, 0]), 1e-12):.1f} |")
    md.append("")

    # ---------------- Q5 absorption at T0
    md.append("## 6. Q5 absorption: truth T0 (β = 0), spurious inferred corruption by clean-law source\n")
    md.append("Prediction: a clean model that is too persistent (η̂ < η = 0.05) reads natural switches as sign flips → β̂ > 0 and harm; η̂ > η → β̂ ≈ 0. Mean β̂ ± replicate sd; harm rate with Wilson 95%; B_pipe mean.\n")
    md.append("| source (η used) | estimator | n | mean β̂ | harm rate [CI] | mean B_pipe |\n|---|---|---|---|---|---|")
    for sname in ("EX", "ETA-", "ETA+", "HMM-1000-s1", "HMM-100000-s1"):
        u = U.get((sname, "T0"))
        if not u:
            continue
        E, bh = arr(u, "E"), arr(u, "bhat")
        eta = u["eta_mom"]
        for k, e in enumerate(ADAPT):
            for n in (100, 1000, 10000):
                ni = u["ns"].index(n)
                kk, nn = harm_counts(u, k, ni)
                p, lo, hi = wilson(kk, nn)
                md.append(f"| {sname} ({eta:.4f}) | {e} | {n} | {np.nanmean(bh[:, ni, k]):.4f} ± {np.nanstd(bh[:, ni, k], ddof=1):.4f} | {p:.2f} [{lo:.2f},{hi:.2f}] | {np.mean(u['E_naive_pipe'] - E[:, ni, k]):+.4f} |")
                out[f"absorb|{sname}|{e}|{n}"] = dict(bhat=float(np.nanmean(bh[:, ni, k])), harm=p)
    md.append("")
    md.append("Moment estimator, raw (unprojected) β̂ at T0 and n = 10,000: " + "; ".join(
        f"{s}: {np.nanmean(arr(U[(s, 'T0')], 'raw')[:, -1, 3]):+.4f}" for s in ("EX", "ETA-", "ETA+", "HMM-1000-s1", "HMM-100000-s1") if (s, "T0") in U) + "\n")

    # ---------------- Q6 off-family
    md.append("## 7. Q6 off-family truths (T5–T7; not in the E2b family or the PP grid), exact law: regret at selected n\n")
    md.append("| truth | n | MLE | MAP | PP (grid, misspecified) | MOM | F-qbar | naive |\n|---|---|---|---|---|---|---|---|")
    for tn in ("T5", "T6", "T7"):
        u = U.get(("EX", tn))
        if not u:
            continue
        E = arr(u, "E")
        for n in (100, 1000, 10000):
            ni = u["ns"].index(n)
            md.append(f"| {tn} | {n} | " + " | ".join(f"{np.nanmean(E[:, ni, k]):.4f}" for k in range(4)) + f" | {u['fixed']['F-qbar']:.4f} | {u['E_naive_pipe']:.4f} |")
    md.append("")

    # ---------------- learned clean laws
    md.append("## 8. Learned clean laws (HMM fits and saved A4 checkpoints): regret by truth, n ∈ {100, 1,000, 10,000}\n")
    md.append("Mean over seeds (5) of replicate-mean regret ± 95% t over seeds (HMM: seeds 1–5 incl. the 20-replicate unit s1; A4: 4 replicates per seed). Fixed: F-qbar and naive under the same clean-law source.\n")
    for fam, pat in (("HMM-100000", "HMM-100000-s"), ("HMM-1000", "HMM-1000-s"), ("A4-100000", "A4-100000-s"), ("A4-1000", "A4-1000-s")):
        md.append(f"**{fam}**\n\n| truth | n | MLE | MAP | PP | MOM | F-qbar | naive | worst harm (any seed, any estimator) |\n|---|---|---|---|---|---|---|---|---|")
        for tn in truths:
            for n in (100, 1000, 10000):
                vals = {k: [] for k in range(4)}
                fq, nv, harm_any = [], [], False
                for s in range(1, 6):
                    u = U.get((f"{pat}{s}", tn))
                    if not u:
                        continue
                    ni = u["ns"].index(n)
                    E = arr(u, "E")
                    for k in range(4):
                        vals[k].append(np.nanmean(E[:, ni, k]))
                        harm_any |= (u["E_naive_pipe"] - E[:, ni, :].min() < 0) and False
                    fq.append(u["fixed"]["F-qbar"])
                    nv.append(u["E_naive_pipe"])
                if not vals[0]:
                    continue
                # harm: pooled share of (seed, replicate) pairs harmed, max over estimators
                kk = [0] * 4
                tot = 0
                for s in range(1, 6):
                    u = U.get((f"{pat}{s}", tn))
                    if not u:
                        continue
                    ni = u["ns"].index(n)
                    for k in range(4):
                        a, b = harm_counts(u, k, ni)
                        kk[k] += a
                    tot += b
                md.append(f"| {tn} | {n} | " + " | ".join("{:.4f} ± {:.4f}".format(*tci(vals[k])) for k in range(4)) + f" | {np.mean(fq):.4f} | {np.mean(nv):.4f} | {max(kk) / max(tot, 1):.2f} |")
        md.append("")

    # ---------------- figures
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        figdir = os.path.dirname(args.out)
        fig, axes = plt.subplots(2, 4, figsize=(16, 7))
        for ax, tn in zip(axes.ravel(), truths):
            u = U.get(("EX", tn))
            if not u:
                continue
            E = arr(u, "E")
            for k, (e, col) in enumerate(zip(ADAPT, ("tab:blue", "tab:orange", "tab:green", "tab:red"))):
                m = np.nanmean(E[:, :, k], axis=0)
                ax.plot(u["ns"], m, marker="o", ms=3, color=col, label=e)
            ax.axhline(u["fixed"]["F-qbar"], color="gray", ls="--", label="F-qbar")
            ax.axhline(u["E_naive_pipe"], color="k", ls=":", label="naive")
            ax.set_xscale("log")
            ax.set_yscale("symlog", linthresh=1e-3)
            ax.set_title(f"{tn}: {TRUTH_DESC[tn]}", fontsize=9)
            ax.set_xlabel("adaptation prefixes n")
        axes[0][0].legend(fontsize=7, frameon=False)
        axes[0][0].set_ylabel("true-law regret")
        fig.tight_layout()
        fig.savefig(os.path.join(figdir, "fig_e3_curves.png"), dpi=110)
        plt.close(fig)
    except Exception as ex:
        md.append(f"(figure skipped: {ex})")
    open(args.out, "w", encoding="utf-8").write("\n".join(md) + "\n")
    json.dump(out, open(os.path.join(base, "analysis.json"), "w"), indent=1)
    print("wrote", args.out)


if __name__ == "__main__":
    main()
