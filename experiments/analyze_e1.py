"""E1 analysis: predeclared comparisons C-a ... C-d (protocol v2, section E1), paired by seed with the pilot's arms.

    python experiments/analyze_e1.py --out docs/reports/e1_tables.md

Delta_min = clip(0.10 V_2, 0.002 VOI_clean, 0.02 VOI_clean) from the pilot's test sets. Verdicts as in analyze_learned.py. Because Delta_min
saturates at N=1e5, each comparison also reports the ratio E_x/E_y as a geometric mean over seeds with a t-interval on the log ratio.
In-family priors for the broad family: P1, P2, P5. Out-of-family (simplex vertices): P3, P4.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRIORS = ["P1", "P2", "P3", "P4", "P5"]
IN_FAMILY = {"P1", "P2", "P5"}
COMPARISONS = [("C-a", "A4", "A6pd-broad"), ("C-b", "A6pd-broad", "A6p-broad"), ("C-c", "A4", "A2-G"), ("C-d", "A4", "A6d"),
               ("extra", "A6d", "A6"), ("extra", "A2-G", "A6pd-broad")]


def tci(x):
    x = np.asarray(x, float)
    return float(x.mean()), float(stats.t.ppf(0.975, len(x) - 1) * x.std(ddof=1) / np.sqrt(len(x)))


def dmin(v2, voi):
    return min(max(0.10 * v2, 0.002 * voi), 0.02 * voi)


def verdict(lo, hi, d, x, y):
    if hi < -d:
        return f"{x} better"
    if lo > d:
        return f"{y} better"
    if lo > -d and hi < d:
        return "equivalent"
    return "inconclusive"


def load(d):
    E, voi, units = defaultdict(dict), {}, []
    for p in sorted(glob.glob(os.path.join(d, "units", "*.json"))):
        u = json.load(open(p))
        units.append(u)
        if "voi_clean" in u:
            voi[u["phys_idx"]] = u["voi_clean"]
        for r in u["rows"]:
            E[(u["phys_idx"], u["N"], r["prior"], r["arm"])][u["seed"]] = r["E"]
    return E, voi, units


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pilot", default=os.path.join(ROOT, "results", "learned_pilot"))
    ap.add_argument("--e1", default=os.path.join(ROOT, "results", "e1"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "reports", "e1_tables.md"))
    args = ap.parse_args()
    Ep, voi, _ = load(args.pilot)
    Ee, _, units = load(args.e1)
    E = {**Ep, **Ee}
    qw = {u["phys_idx"]: u["q_w"] for u in units}
    prov = units[0]["provenance"]
    md = [f"_Generated by `experiments/analyze_e1.py`. E1 code commit `{prov['git_commit'][:10]}` (dirty code files: {prov['dirty_code_files'] or 'none'}); pilot arms read from `results/learned_pilot/`; seeds {sorted({u['seed'] for u in units})}._\n"]
    md.append("## Endpoint E of the new arms (mean over seeds ± 95% t-interval) next to the pilot's reference arms\n")
    out = {}
    for p in (0, 1):
        for N in (1000, 100000):
            md.append(f"\n**q_w={qw[p]}, N={N}**\n\n| arm | " + " | ".join(PRIORS) + " |\n|---|" + "---|" * 5)
            for arm in ["exact-naive", "A4", "A2-G", "A6p-broad", "A6", "A6pd-broad", "A6d"]:
                cells = []
                for pr in PRIORS:
                    v = E.get((p, N, pr, arm))
                    cells.append("—" if not v else "{:.4f} ± {:.4f}".format(*tci(list(v.values()))) if len(v) > 1 else f"{list(v.values())[0]:.4f}")
                md.append(f"| {arm} | " + " | ".join(cells) + " |")
    md.append("\n## Predeclared comparisons (d = E_x − E_y, negative: x better; ratio = E_x/E_y)\n")
    md.append("| id | x | y | physics | N | prior | family | d ± CI | Δ_min | verdict | ratio E_x/E_y (95% CI) |\n|---|---|---|---|---|---|---|---|---|---|---|")
    tally = defaultdict(lambda: defaultdict(int))
    for cid, x, y in COMPARISONS:
        for p in (0, 1):
            for N in (1000, 100000):
                for pr in PRIORS:
                    rx, ry = E.get((p, N, pr, x)), E.get((p, N, pr, y))
                    rn = E.get((p, N, pr, "exact-naive"))
                    if not rx or not ry or len(set(rx) & set(ry)) < 2:
                        continue
                    seeds = sorted(set(rx) & set(ry))
                    d = [rx[s] - ry[s] for s in seeds]
                    m, h = tci(d)
                    dm = dmin(float(np.mean(list(rn.values()))), voi[p])
                    v = verdict(m - h, m + h, dm, x, y)
                    lr = np.log([rx[s] / ry[s] for s in seeds])
                    lm, lh = tci(lr)
                    fam = "in-family" if pr in IN_FAMILY else "out-of-family"
                    md.append(f"| {cid} | {x} | {y} | q_w={qw[p]} | {N} | {pr} | {fam} | {m:+.4f} ± {h:.4f} | {dm:.4f} | {v} | {np.exp(lm):.2f} ({np.exp(lm - lh):.2f}–{np.exp(lm + lh):.2f}) |")
                    tally[(cid, x, y, N, fam)][v] += 1
                    out[f"{cid}|{p}|{N}|{pr}"] = dict(x=x, y=y, d=m, half95=h, dmin=dm, verdict=v, ratio=float(np.exp(lm)))
    md.append("\n## Verdict tally by comparison, N and prior family\n\n| id | x | y | N | family | tally |\n|---|---|---|---|---|---|")
    for (cid, x, y, N, fam), c in sorted(tally.items()):
        md.append(f"| {cid} | {x} | {y} | {N} | {fam} | " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items())) + " |")
    md.append("\n## Training cost of the new arms (mean over seeds; one thread)\n\n| physics | N | arm | params | epochs run | steps | view-passes | seconds |\n|---|---|---|---|---|---|---|---|")
    for p in (0, 1):
        for N in (1000, 100000):
            us = [u for u in units if u["phys_idx"] == p and u["N"] == N]
            for arm in us[0]["train"]:
                t = [u["train"][arm] for u in us]
                md.append(f"| q_w={qw[p]} | {N} | {arm} | {t[0]['params']} | {np.mean([x['epochs_run'] for x in t]):.1f} | {np.mean([x['steps'] for x in t]):.0f} | {np.mean([x['view_passes'] for x in t]):.2e} | {np.mean([x['seconds'] for x in t]):.0f} |")
    open(args.out, "w", encoding="utf-8").write("\n".join(md) + "\n")
    json.dump(out, open(os.path.join(args.e1, "analysis.json"), "w"), indent=1)
    print("wrote", args.out)


if __name__ == "__main__":
    main()
