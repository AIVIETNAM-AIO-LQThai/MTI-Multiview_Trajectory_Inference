"""Aggregate learned-pilot units: seed-level t-intervals, captured opportunity, paired comparisons judged against Delta_min.

    python experiments/analyze_learned.py --in results/learned_pilot --out docs/reports/learned_pilot_tables.md

Endpoint E = E[kappa (mu_hat - mu_2)^2] (exact aware oracle gives 0; the exact naive filter gives V_2).
Delta_min = clip(0.10 V_2, 0.002 VOI_clean, 0.02 VOI_clean) per (physics, prior).
Uncertainty = t-interval over training seeds; paired differences use the same seed index for both arms.
Verdict for a difference d = E_x - E_y (negative: x better): x better if upper CI < -Delta; y better if lower CI > Delta;
equivalent if the CI lies inside (-Delta, Delta); otherwise inconclusive.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRIORS = ["P1", "P2", "P3", "P4", "P5"]
ARM_ORDER = ["A0-oracle", "exact-naive", "A1", "A1r", "A5", "A4", "A2-G", "A2-M", "A2-avg", "A3-ens", "A6", "A6p-narrow", "A6p-broad"]
PAIRS = [("A2-G", "A2-M"), ("A2-G", "A2-avg"), ("A2-M", "A2-avg"), ("A2-G", "A3-ens"), ("A2-G", "A4"), ("A2-M", "A4"), ("A4", "A5"),
         ("A2-G", "A5"), ("A2-G", "A6p-broad"), ("A2-G", "A6"), ("A2-G", "A1r"), ("A4", "A6p-broad"), ("A6p-narrow", "A6p-broad"), ("A2-G", "A1")]


def tci(x):
    x = np.asarray(x, float)
    n = len(x)
    if n < 2:
        return float(x.mean()), float("nan")
    return float(x.mean()), float(stats.t.ppf(0.975, n - 1) * x.std(ddof=1) / np.sqrt(n))


def dmin(v2, voi):
    return min(max(0.10 * v2, 0.002 * voi), 0.02 * voi)


def verdict(lo, hi, d, x, y):
    if hi < -d:
        return f"{x} better (≥Δ)"
    if lo > d:
        return f"{y} better (≥Δ)"
    if lo > -d and hi < d:
        return "equivalent (±Δ)"
    return "inconclusive"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", default=os.path.join(ROOT, "results", "learned_pilot"))
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "reports", "learned_pilot_tables.md"))
    args = ap.parse_args()
    units = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(args.inp, "units", "*.json")))]
    E = defaultdict(dict)      # (phys, N, prior, arm) -> {seed: row}
    meta = {}
    for u in units:
        meta[(u["phys_idx"], u["N"], u["seed"])] = u
        for r in u["rows"]:
            E[(u["phys_idx"], u["N"], r["prior"], r["arm"])][u["seed"]] = r
    phys_ids = sorted({k[0] for k in E})
    Ns = sorted({k[1] for k in E})
    md = []
    prov = units[0]["provenance"]
    seeds = sorted({u["seed"] for u in units})
    md.append(f"_Generated by `experiments/analyze_learned.py`. Code commit `{prov['git_commit'][:10]}` (dirty code files: {prov['dirty_code_files'] or 'none'}), torch {prov['torch']}, seeds {seeds}, test prefixes {units[0]['n_test']}._\n")
    ref = {}                   # (phys, prior) -> (V2, VOI, Dmin)
    for p in phys_ids:
        voi = float(np.mean([u["voi_clean"] for u in units if u["phys_idx"] == p]))
        for pr in PRIORS:
            rows = E.get((p, Ns[0], pr, "exact-naive"))
            if rows:
                v2 = float(np.mean([r["E"] for r in rows.values()]))
                ref[(p, pr)] = (v2, voi, dmin(v2, voi))
    qw = {u["phys_idx"]: u["q_w"] for u in units}
    md.append("## Reference points and Δ_min (from the test set of this run)\n")
    md.append("| physics | prior | V_2 = E(exact naive) | VOI_clean | Δ_min |\n|---|---|---|---|---|")
    for (p, pr), (v2, voi, d) in sorted(ref.items()):
        md.append(f"| q_w={qw[p]} | {pr} | {v2:.4f} | {voi:.3f} | {d:.4f} |")
    out_json = {}
    for p in phys_ids:
        for N in Ns:
            md.append(f"\n## Endpoint E by arm — physics q_w={qw[p]}, N={N}\n")
            md.append("Mean over seeds ± 95% t-interval (n seeds in header); in brackets the captured opportunity 1 − E/V_2 (exact aware = 100%, exact naive = 0%).\n")
            nseed = len({s for (pp, nn, s) in meta if pp == p and nn == N})
            md.append(f"| arm (n={nseed}) | " + " | ".join(PRIORS) + " |\n|---|" + "---|" * len(PRIORS))
            for arm in ARM_ORDER:
                cells = []
                for pr in PRIORS:
                    rows = E.get((p, N, pr, arm))
                    if not rows:
                        cells.append("—")
                        continue
                    m, h = tci([r["E"] for r in rows.values()])
                    v2 = ref[(p, pr)][0]
                    cells.append(f"{m:.4f} ± {h:.4f} [{100 * (1 - m / v2):.0f}%]" if arm not in ("A0-oracle",) else "0")
                    out_json[f"{p}|{N}|{pr}|{arm}"] = dict(mean=m, half95=h, captured=1 - m / v2)
                md.append(f"| {arm} | " + " | ".join(cells) + " |")
            md.append("| *Δ_min* | " + " | ".join(f"{ref[(p, pr)][2]:.4f}" for pr in PRIORS) + " |")
            md.append(f"\n### Paired comparisons (d = E_x − E_y, negative: x better) — physics q_w={qw[p]}, N={N}\n")
            md.append("| x | y | prior | d ± 95% CI | Δ_min | CI half-width ≤ Δ_min/2 | verdict |\n|---|---|---|---|---|---|---|")
            for x, y in PAIRS:
                for pr in PRIORS:
                    rx, ry = E.get((p, N, pr, x)), E.get((p, N, pr, y))
                    if not rx or not ry:
                        continue
                    common = sorted(set(rx) & set(ry))
                    d_ = [rx[s]["E"] - ry[s]["E"] for s in common]
                    m, h = tci(d_)
                    dm = ref[(p, pr)][2]
                    md.append(f"| {x} | {y} | {pr} | {m:+.4f} ± {h:.4f} | {dm:.4f} | {'yes' if h <= dm / 2 else 'no'} | {verdict(m - h, m + h, dm, x, y)} |")
                    out_json[f"pair|{p}|{N}|{pr}|{x}|{y}"] = dict(d=m, half95=h, dmin=dm, verdict=verdict(m - h, m + h, dm, x, y))
    # mechanism diagnostics
    md.append("\n## Mechanism diagnostics (realised-cost difference D vs the exact naive action; negative = cheaper than exact naive)\n")
    md.append("D_none = on uncorrupted records; D_switch = in the natural-switch stratum E_{L−1} (hidden path); mean over seeds ± 95% t-interval. The exact aware oracle's own values are the reference.\n")
    for p in phys_ids:
        for N in Ns:
            md.append(f"\n**q_w={qw[p]}, N={N}, prior P1**\n\n| arm | D | D_none | D_switch | E_none | E_cor |\n|---|---|---|---|---|---|")
            for arm in ARM_ORDER[:1] + ARM_ORDER[2:]:
                rows = E.get((p, N, "P1", arm))
                if not rows:
                    continue
                f = lambda k: "{:+.3f} ± {:.3f}".format(*tci([r[k] for r in rows.values()]))
                g = lambda k: "{:.4f} ± {:.4f}".format(*tci([r[k] for r in rows.values()]))
                md.append(f"| {arm} | {f('D')} | {f('D_none')} | {f('D_switch')} | {g('E_none')} | {g('E_cor')} |")
    md.append("\n## Route gap of the shared model (A2): G − M under each prior (identity Ĝ−M̂ = Ẑ⁻¹Σ q_j Ĉ_j/(1−r̂_j) verified numerically)\n")
    md.append("| physics | N | prior | mean signed gap (RB) | gap on clean records | gap on corrupted records | E[κ gap²] | mean ‖Ĉ_j‖ | max identity error |\n|---|---|---|---|---|---|---|---|---|")
    for p in phys_ids:
        for N in Ns:
            for pr in PRIORS:
                rows = E.get((p, N, pr, "A2-G"))
                if not rows:
                    continue
                f = lambda k: "{:+.4f} ± {:.4f}".format(*tci([r[k] for r in rows.values()]))
                md.append(f"| q_w={qw[p]} | {N} | {pr} | {f('gap_signed')} | {f('gap_signed_none')} | {f('gap_signed_cor')} | "
                          f"{np.mean([r['gap_ksq'] for r in rows.values()]):.5f} | {np.mean([r['C_abs'] for r in rows.values()]):.4f} | "
                          f"{max(r['gap_identity_max_err'] for r in rows.values()):.1e} |")
    md.append("\n## Query-level errors of the shared model against exact conditionals (κ-weighted mean squared error; unweighted over views; mean over seeds)\n")
    md.append("Contamination count = action signs differing from H in the query. Folded counts: 0 = clean/attacked slot, 1 = retains a flip.\n")
    keys = ["full_kmse_clean_records", "full_kmse_corrupted_records", "flip_kmse_c0", "flip_kmse_c1", "flip_kmse_c2", "folded_psi_kmse_c0",
            "folded_psi_kmse_c1", "sign_kl_c0", "sign_kl_c1"]
    md.append("| physics | N | " + " | ".join(keys) + " |\n|---|---|" + "---|" * len(keys))
    for p in phys_ids:
        for N in Ns:
            us = [u for u in units if u["phys_idx"] == p and u["N"] == N]
            md.append(f"| q_w={qw[p]} | {N} | " + " | ".join(
                f"{np.mean([u['query_diagnostics'][k] for u in us if u['query_diagnostics'][k] is not None]):.4f}" for k in keys) + " |")
    md.append("\n## Training / inference cost (mean over seeds)\n")
    md.append("| physics | N | arm | params | epochs run | steps | view-passes | train seconds (1 thread) | queries per test record |\n|---|---|---|---|---|---|---|---|---|")
    qpr = units[0]["queries_per_record"]
    for p in phys_ids:
        for N in Ns:
            us = [u for u in units if u["phys_idx"] == p and u["N"] == N]
            for arm in us[0]["train"]:
                t = [u["train"][arm] for u in us]
                q = {"A1": "A1", "A2": "A2-G / A2-M", "A4": "A4", "A6": "A6", "A6p-narrow": "A6p-narrow", "A6p-broad": "A6p-broad"}[arm]
                qq = qpr["A2-G"] if arm == "A2" else qpr[arm]
                qs = f"{qpr['A2-G']} (G) / {qpr['A2-M']} (M)" if arm == "A2" else qq
                md.append(f"| q_w={qw[p]} | {N} | {arm} | {t[0]['params']} | {np.mean([x['epochs_run'] for x in t]):.1f} | {np.mean([x['steps'] for x in t]):.0f} | "
                          f"{np.mean([x['view_passes'] for x in t]):.2e} | {np.mean([x['seconds'] for x in t]):.0f} | {qs} |")
            md.append(f"| q_w={qw[p]} | {N} | A5 (EM) | 1 | — | — | — | — | analytic |")
        etas = [u["eta_hat"] for u in units if u["phys_idx"] == p]
        md.append(f"\nA5 fitted η̂ (true 0.05) q_w={qw[p]}: " + ", ".join(f"N={N}: {np.mean([u['eta_hat'] for u in units if u['phys_idx'] == p and u['N'] == N]):.4f} "
                  f"(sd {np.std([u['eta_hat'] for u in units if u['phys_idx'] == p and u['N'] == N], ddof=1):.4f})" for N in Ns) + "\n")
    open(args.out, "w", encoding="utf-8").write("\n".join(md) + "\n")
    json.dump(out_json, open(os.path.join(args.inp, "analysis.json"), "w"), indent=1)
    print("wrote", args.out)


if __name__ == "__main__":
    main()
